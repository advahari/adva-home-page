function openModal(item, sourceButton) {
  lastFocusedButton = sourceButton;
  modalTitle.textContent = item.title;
  modalSubtitle.textContent = item.subtitle;
  modalIcon.textContent = item.icon;
  modalContent.innerHTML = item.content;
  modalCta.textContent = item.cta;
  modalOverlay.classList.add('open');
  modalOverlay.setAttribute('aria-hidden', 'false');
  document.body.classList.add('no-scroll');
  modalClose.focus();
}

function closeModal() {
  modalOverlay.classList.remove('open');
  modalOverlay.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('no-scroll');
  if (lastFocusedButton) {
    lastFocusedButton.focus();
  }
}

function trapModalFocus(event) {
  if (!modalOverlay.classList.contains('open') || event.key !== 'Tab') {
    return;
  }

  const focusable = modalOverlay.querySelectorAll(
    'button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])'
  );
  if (!focusable.length) {
    return;
  }

  const first = focusable[0];
  const last = focusable[focusable.length - 1];

  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
}

